import { Transform } from 'class-transformer';
import { IsEmail, IsEnum, IsNotEmpty, IsString, MaxLength } from 'class-validator';
import { trim } from '../../common/transforms.js';

export enum UserRole {
  Admin = 'admin',
  Staff = 'staff',
}

export enum UserStatus {
  Active = 'active',
  Disabled = 'disabled',
}

/** Emails are compared and stored trimmed and lowercased (users_email_key is case-insensitive that way). */
export const normalizeEmail = ({ value }: { value: unknown }): unknown =>
  typeof value === 'string' ? value.trim().toLowerCase() : value;

/** The password is generated by the server and returned once; the user replaces it at first sign-in. */
export class CreateUserDto {
  @Transform(trim)
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  fullName: string;

  @Transform(normalizeEmail)
  @IsEmail({}, { message: 'email must be an email address' })
  @MaxLength(200)
  email: string;

  @IsEnum(UserRole)
  role: UserRole;
}
